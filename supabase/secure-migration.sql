drop policy if exists "Authenticated staff can read school metadata" on public.app_storage;
create policy "Authenticated staff can read school metadata"
on public.app_storage for select
to authenticated
using (key = 'school-meta');

drop policy if exists "Admins can manage school metadata" on public.app_storage;
create policy "Admins can manage school metadata"
on public.app_storage for all
to authenticated
using (key = 'school-meta' and public.current_staff_role() = 'admin')
with check (key = 'school-meta' and public.current_staff_role() = 'admin');

drop policy if exists "Staff can read own profile" on public.staff_profiles;
create policy "Staff can read own profile"
on public.staff_profiles for select
to authenticated
using (id = auth.uid() or public.current_staff_role() = 'admin');

drop policy if exists "Authenticated staff can read products" on public.products;
create policy "Authenticated staff can read products"
on public.products for select
to authenticated
using (true);

drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
on public.products for all
to authenticated
using (public.current_staff_role() = 'admin')
with check (public.current_staff_role() = 'admin');

drop policy if exists "Managers can edit products" on public.products;
create policy "Managers can edit products"
on public.products for update
to authenticated
using (public.current_staff_role() in ('admin', 'manager'))
with check (public.current_staff_role() in ('admin', 'manager'));

drop policy if exists "Authenticated staff can read orders" on public.orders;
create policy "Authenticated staff can read orders"
on public.orders for select
to authenticated
using (public.current_staff_role() in ('admin', 'manager') or cashier_id = auth.uid());

drop policy if exists "Staff can create own orders" on public.orders;
create policy "Staff can create own orders"
on public.orders for insert
to authenticated
with check (cashier_id = auth.uid());

drop policy if exists "Authenticated staff can read order items" on public.order_items;
create policy "Authenticated staff can read order items"
on public.order_items for select
to authenticated
using (exists (
  select 1 from public.orders o
  where o.id = order_items.order_id
    and (public.current_staff_role() in ('admin', 'manager') or o.cashier_id = auth.uid())
));

drop policy if exists "Staff can create order items" on public.order_items;
create policy "Staff can create order items"
on public.order_items for insert
to authenticated
with check (exists (
  select 1 from public.orders o
  where o.id = order_items.order_id and o.cashier_id = auth.uid()
));

